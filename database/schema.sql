CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sources (
 id INTEGER PRIMARY KEY, name TEXT NOT NULL, url TEXT NOT NULL UNIQUE, enabled INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS keywords (id INTEGER PRIMARY KEY, word TEXT NOT NULL, folded TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS runs (
 id INTEGER PRIMARY KEY, finished TEXT, checked INTEGER DEFAULT 0, discovered INTEGER DEFAULT 0,
 matched INTEGER DEFAULT 0, fresh INTEGER DEFAULT 0, notification TEXT DEFAULT '');
CREATE TABLE IF NOT EXISTS checks (
 run INTEGER REFERENCES runs, name TEXT, url TEXT, status TEXT, count INTEGER, message TEXT);
CREATE TABLE IF NOT EXISTS jobs (
 id INTEGER PRIMARY KEY, first_run INTEGER REFERENCES runs, last_run INTEGER REFERENCES runs,
 title TEXT, company TEXT, url TEXT, description TEXT, location TEXT, employment TEXT, published TEXT);
CREATE TABLE IF NOT EXISTS identities (key TEXT PRIMARY KEY, job INTEGER NOT NULL REFERENCES jobs);
